# ---------------------------------------------------------------- auth

# Signed token secret derived from the existing encryption key (never hard-coded).
_TTL = 60 * 60 * 24 * 7  # sessions last 7 days
_serializer = URLSafeTimedSerializer(ENV_ENCRYPTION_KEY or "hostbot-dashboard-secret")


def _make_token(user_id: int) -> str:
    return _serializer.dumps({"uid": user_id})


def _read_token() -> dict | None:
    header = request.headers.get("Authorization", "")
    if not header.startswith("Bearer "):
        return None
    token = header[7:].strip()
    try:
        data = _serializer.loads(token, max_age=_TTL)
        return data if isinstance(data, dict) else None
    except (BadSignature, SignatureExpired):
        return None


app = Flask(__name__)
app.config["JSON_SORT_KEYS"] = False


def _require_user() -> dict:
    data = _read_token()
    if not data:
        raise PermissionError("Not authenticated")
    return data


def _is_admin_uid(uid: int) -> bool:
    if uid == OWNER_ID:
        return True
    if uid in ADMIN_IDS:
        return True
    try:
        if uid in database.db_load_admins():
            return True
    except Exception:
        pass
    return False


def _make_admin_token(user_id: int) -> str:
    return _serializer.dumps({"uid": user_id, "admin": True})


def _require_admin() -> dict:
    data = _read_token()
    if not data or not data.get("admin"):
        raise PermissionError("Not authenticated")
    if not _is_admin_uid(data["uid"]):
        raise PermissionError("Forbidden")
    return data


