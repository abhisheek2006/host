@app.post("/api/login")
def api_login():
    code = (request.get_json(silent=True) or {}).get("code", "").strip()
    if not code:
        return jsonify({"error": "Code is required"}), 400

    database.db_delete_login_code_expired()
    # Login codes are indexed by user_id; find any matching unexpired code.
    found = None
    for row in database.login_col.find({"code": code}):
        try:
            expires = datetime.fromisoformat(row["expires_at"])
        except (ValueError, KeyError):
            continue
        if expires > datetime.utcnow():
            found = row
            break

    if not found:
        return jsonify({"error": "Invalid or expired code"}), 401

    user_id = found["user_id"]
    database.db_delete_login_code(user_id)
    return jsonify({"token": _make_token(user_id), "user_id": user_id})


